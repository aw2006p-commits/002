    fun getQuizForCategory(category: LessonCategory): UnifiedQuiz {
        val specific = categoryQuizzes[category] ?: generateCategoryQuestions(category)
        return UnifiedQuiz(
            id = "cat_${category.name}",
            title = "الاختبار الشامل لخاتمة قسم${category.displayName}",
            subtitle = "امتحان التمكين والتحصيل العلمي الدقيق لكافة مسائل وفوائد هذا القسم",
            badgeLabel = "امتحان شامل للقسم",
            quizType = QuizType.SECTION,
            category = category,
            difficulty = "مستوى متقدم جدا • خاتمة القسم",
            questions = specific
        )
    }

    private fun generateCategoryQuestions(category: LessonCategory): List<QuizQuestion> {
        val lessons = SheikhData.allLessons.filter { it.category == category }
        val pool = mutableListOf<QuizQuestion>()
        for (lesson in lessons) {
            pool.addAll(generateScholarlyQuestions(lesson))
        }
        return if (pool.size >= 5) pool.take(5) else pool
    }

    private fun formatTimestamp(seconds: Long): String {
        val m = seconds / 60
        val s = seconds % 60
        return String.format("%02d:%02d", m, s)
    }

    fun getUnifiedQuizForLesson(lesson: Lesson): UnifiedQuiz {
        val lessonQuiz = getQuizForLesson(lesson)
        return UnifiedQuiz(
            id = lesson.id,
            title = "اختبار درس:${lesson.title}",
            subtitle = "سلسلة:${lesson.series} • ${lesson.category.displayName}",
            badgeLabel = "اختبار الدرس",
            quizType = QuizType.LESSON,
            category = lesson.category,
            difficulty = lessonQuiz.difficulty,
            questions = lessonQuiz.questions
        )
    }

    fun getQuizForLesson(lesson: Lesson): LessonQuiz {
        // Return tailored quiz if explicitly mapped
        val specificQuestions = lessonQuizzes[lesson.id]
        if (specificQuestions != null && specificQuestions.isNotEmpty()) {
            val enriched = specificQuestions.mapIndexed { index, q ->
                val fallbackTime = ((index + 1) * 180L).coerceAtMost((lesson.durationSeconds - 30L).coerceAtLeast(60L))
                q.copy(
                    lessonId = q.lessonId ?: lesson.id,
                    timestampSeconds = if (q.timestampSeconds > 0) q.timestampSeconds else fallbackTime,
                    timestampLabel = if (q.timestampSeconds > 0) q.timestampLabel else formatTimestamp(fallbackTime)
                )
            }
            return LessonQuiz(
                lessonId = lesson.id,
                lessonTitle = lesson.title,
                series = lesson.series,
                questions = enriched
            )
        }

        // Generate tailored high-level questions based on lesson metadata, category, and takeaways
        val generatedQuestions = generateScholarlyQuestions(lesson)
        return LessonQuiz(
            lessonId = lesson.id,
            lessonTitle = lesson.title,
            series = lesson.series,
            questions = generatedQuestions
        )
    }

